#!/usr/bin/env python3
"""Give an explainer a music bed composed with ElevenLabs Music.

    python3 scripts/explainer_music.py p1-outage              # the plan and what exists; spends nothing
    python3 scripts/explainer_music.py p1-outage --generate   # compose the source (paid), then build the bed
    python3 scripts/explainer_music.py p1-outage --bed        # rebuild the bed from the source already here (free)

script.json carries the brief:
  "music": {"model": "music_v1", "tail": 2.6, "levels": [[0, -24], [1.2, -27]], "ending": -20,
            "plan": {"positive_global_styles": [...], "negative_global_styles": [...],
                     "sections": [{"section_name": "...", "positive_local_styles": [...],
                                   "negative_local_styles": [], "duration_ms": 13430, "lines": []}, ...]}}

Section lengths should add up to the film (narration plus the scene's tail), so the music turns
where the film turns. "levels" are loudness in LUFS at authored times, linear between points; the
voice sits at -16, so -28 is twelve below it. After the last word the bed lifts to "ending" and
fades out.

Writes, beside the scene:
  music-source.mp3   the composition as it came back. Kept in git: composing again gives a different piece.
  music.mp3          the film-length bed, levelled under the voice. The page plays it; the renderer mixes it in.
  music.json         what was asked for, when, and the hashes and measured loudness of both files.
and names the bed in narration.js. Run --bed again after re-voicing or changing the levels.

Composing costs credits. The key comes from ELEVENLABS_API_KEY or ~/.elevenlabs.io. Requires ffmpeg.
"""
from pathlib import Path
import argparse,datetime,hashlib,json,re,subprocess,sys,urllib.error,urllib.request
ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(Path(__file__).resolve().parent))
from explainer_narration import api_key,warp  # noqa: E402
PREFIX='// Generated by scripts/explainer_narration.py. Do not edit.\nwindow.EXPLAINER_NARRATION='
def sha(path):return hashlib.sha256(path.read_bytes()).hexdigest()
def compose(plan,model):
    req=urllib.request.Request('https://api.elevenlabs.io/v1/music?output_format=mp3_44100_192',data=json.dumps({'composition_plan':plan,'model_id':model}).encode(),
        headers={'Content-Type':'application/json','xi-api-key':api_key()},method='POST')
    try:
        with urllib.request.urlopen(req,timeout=900) as response:return response.read(),response.headers.get('song-id')
    except urllib.error.HTTPError as error:
        raise SystemExit(f'ElevenLabs returned {error.code}: {error.read().decode()[:400]}')
def real_time(table,a):
    """The time in the current take of an authored time, through the warp table."""
    for (r0,a0),(r1,a1) in zip(table,table[1:]):
        if a<=a1:return r0+(r1-r0)*(a-a0)/(a1-a0) if a1>a0 else r0
    return table[-1][0]+(a-table[-1][1])
def lufs(path,start=0,length=None):
    cut=['-ss',f'{start:.2f}']+(['-t',f'{length:.2f}'] if length else [])
    text=subprocess.run(['ffmpeg','-nostdin','-hide_banner',*cut,'-i',str(path),'-af','ebur128','-f','null','-'],capture_output=True,text=True).stderr
    return float(re.findall(r'I:\s+(-?[\d.]+) LUFS',text)[-1])
def bed(home,cfg,total,table):
    """music.mp3: the source from its start, entering at cfg['enter'], held at cfg['levels'], lifted and faded after the last word."""
    tail=cfg.get('tail',2.6);enter=real_time(table,cfg.get('enter',0));length=total+tail-enter
    points=[[max(0,real_time(table,a)-enter),db] for a,db in cfg.get('levels',[[0,-28]])]
    base=points[0][1];points+=[[total-enter-.2,points[-1][1]],[total-enter+.8,cfg.get('ending',-22)]]
    expr=str(points[-1][1]-base)  # dB relative to the loudnorm target
    for (t0,d0),(t1,d1) in reversed(list(zip(points,points[1:]))):
        if t1>t0:expr=f'if(lt(t,{t1:.3f}),{d0-base}+({d1-d0})*clip((t-{t0:.3f})/{t1-t0:.3f},0,1),{expr})'
    chain=(f'atrim=start={cfg.get("offset",0)}:duration={length:.3f},asetpts=PTS-STARTPTS,loudnorm=I={base}:LRA=7:TP=-9,aresample=44100,'
        f"volume=eval=frame:volume='pow(10,({expr})/20)',afade=t=in:st=0:d={cfg.get('fade_in',.05)},afade=t=out:st={length-1.8:.3f}:d=1.8,"
        f'adelay={int(enter*1000)}:all=1,apad=whole_dur={total+tail:.3f},asetpts=N/SR/TB')
    out=home/'music.mp3'
    subprocess.run(['ffmpeg','-nostdin','-y','-v','error','-i',str(home/'music-source.mp3'),'-af',chain,'-ar','44100','-ac','2','-b:a','128k',str(out)],check=True)
    return out,lufs(out,enter+2,max(1,total-enter-2))
def main():
    p=argparse.ArgumentParser(description=__doc__,formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument('name');p.add_argument('--generate',action='store_true',help='compose the source with ElevenLabs Music (paid)')
    p.add_argument('--bed',action='store_true',help='rebuild the bed from the existing source');a=p.parse_args()
    home=ROOT/'explainers'/a.name;cfg=json.loads((home/'script.json').read_text()).get('music')
    if not cfg:raise SystemExit(f'explainers/{a.name}/script.json has no "music" block')
    narration=json.loads((home/'narration.json').read_text());authored=json.loads((home/'authored.json').read_text())
    total=narration['duration'];film=total+cfg.get('tail',2.6);table=warp(narration['lines'],total,authored)
    sections=cfg['plan']['sections'];planned=sum(s['duration_ms'] for s in sections)/1000;source=home/'music-source.mp3';record_path=home/'music.json'
    print(f'{a.name}: film {film:.1f} s, music planned {planned:.1f} s in {len(sections)} sections on {cfg.get("model","music_v1")}; source {"present" if source.exists() else "not composed yet"}')
    for s in sections:print(f'  {s["duration_ms"]/1000:6.1f} s  {s["section_name"]}: {", ".join(s["positive_local_styles"])}')
    record=json.loads(record_path.read_text()) if record_path.exists() else {}
    if a.generate:
        audio,song=compose(cfg['plan'],cfg.get('model','music_v1'));source.write_bytes(audio)
        record={'provider':'ElevenLabs Music','model':cfg.get('model','music_v1'),'composed':datetime.datetime.now(datetime.timezone.utc).strftime('%Y-%m-%d'),'song_id':song,'plan':cfg['plan']}
        print(f'composed {source.relative_to(ROOT)} ({len(audio)/1e6:.1f} MB)')
    if not source.exists():print('Nothing composed. Add --generate to compose the source (paid).');return
    if not (a.generate or a.bed or not (home/'music.mp3').exists()):print('Bed left as it is. Add --bed to rebuild it.');return
    out,under=bed(home,cfg,total,table)
    length=float(subprocess.run(['ffprobe','-v','error','-show_entries','format=duration','-of','csv=p=0',str(source)],capture_output=True,text=True,check=True).stdout)
    record.update({'source':source.name,'source_sha256':sha(source),'source_seconds':round(length,2),'bed':out.name,'bed_sha256':sha(out),'bed_lufs_under_voice':under,
        'levels':cfg.get('levels'),'ending':cfg.get('ending')});record_path.write_text(json.dumps(record,indent=1)+'\n')
    js=home/'narration.js';text=js.read_text()
    if not text.startswith(PREFIX):raise SystemExit('narration.js is not in the form explainer_narration.py writes')
    compact=json.loads(text[len(PREFIX):].rstrip().rstrip(';'));compact['music']=out.name
    js.write_text(PREFIX+json.dumps(compact,ensure_ascii=False,separators=(',',':'))+';\n')
    print(f'{out.relative_to(ROOT)}: {film:.1f} s, {under:.1f} LUFS under the voice (source is {length:.1f} s)')
if __name__=='__main__':main()
